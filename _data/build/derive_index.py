"""Counts for the index page, read from the claims files themselves.

The index used to carry hand-typed claim counts per card. They drifted the moment a
claim was added anywhere else — the page said 61 while the harness said 62, and said
"sixteen pieces" next to a figure reading 17. Numbers a human retypes are numbers that
go stale, so these are generated.
"""
import json, os, glob

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.abspath(os.path.join(HERE, "..", ".."))
# funding-map and timeline predate the shared core. The comment here used to say they
#   carry no claims; they carry 22 and 31. The flag marks provenance, not emptiness.
LEGACY = {"funding-map", "timeline"}   # predate the shared core; the flag is provenance

pages = {}
for p in sorted(glob.glob(os.path.join(WEB, "*", "claims.json"))):
    slug = os.path.basename(os.path.dirname(p))
    if slug == "index":
        continue
    spec = json.load(open(p, encoding="utf-8"))
    cl = spec.get("claims", [])
    pages[slug] = {"claims": len(cl),
                   "manual": sum(1 for c in cl if c.get("verify") == "manual")}

# every artifact folder that renders, whether or not it carries claims
arts = sorted(d for d in os.listdir(WEB)
              if os.path.isdir(os.path.join(WEB, d))
              and not d.startswith(("_", "."))
              and d not in ("dist", "tools", "node_modules", "shots", "index")
              and os.path.exists(os.path.join(WEB, d, "index.html")))
for a in arts:
    pages.setdefault(a, {"claims": 0, "manual": 0, "legacy": a in LEGACY})

out = {"n_pieces": len(arts),
       "total_claims": sum(v["claims"] for v in pages.values()),
       "total_manual": sum(v["manual"] for v in pages.values()),
       "pages": pages,
       "note": "Generated by derive_index.py from each artifact's claims.json. Never "
               "hand-edit — the index's own claim asserts these match the harness."}
p = os.path.join(WEB, "index", "data", "counts.json")
os.makedirs(os.path.dirname(p), exist_ok=True)
# Trailing newline, so a rebuild is byte-identical to the shipped file. Without it every
# regeneration showed a one-line diff on the last brace, which trains a reader of
# `git status` to expect noise from the one command the note above tells them to run.
with open(p, "w", encoding="utf-8") as fh:
    json.dump(out, fh, indent=1)
    fh.write("\n")
print(f"wrote {p}\n  {out['n_pieces']} pieces, {out['total_claims']} claims, "
      f"{out['total_manual']} manual")
