/* Prefer the JSON the bundler inlined; fall back to fetch when the folder is served
   directly. One call site, both modes — the source tree and the published artifact never
   diverge, and a bundled page needs no network at all. */
function loadData(file) {
  var tag = document.querySelector(
    'script[type="application/json"][data-pv-file="' + file + '"]');
  if (tag) return Promise.resolve(JSON.parse(tag.textContent));
  return fetch('data/' + file, {cache: 'no-cache'}).then(function (r) {
    if (!r.ok) throw new Error(r.status + ' ' + r.statusText);
    return r.json();
  });
}

/* =========================================================================
   PIC portfolio timeline
   Vanilla JS, inline SVG. No dependencies, no build step. Everything on this
   page derives from data/timeline.json, which is generated by
   tools/build-timeline-web.py from the merged event inventory. Do not edit the
   JSON by hand — regenerate it.

   Structure
     1  data + scales
     2  layout        lane bands, collision packing, label placement
     3  render        svg (wide) / cards (narrow)
     4  table + csv
     5  interaction   filters, hover, panel, hash routing
   ========================================================================= */

(() => {
  'use strict';

  // Below this the lanes stop being readable as lanes and a card list is honest.
  const CARD_BREAKPOINT = 900;
  // The window. 99 of 104 public events fall inside it; the five older ones are
  // summarized in a band above rather than compressing the axis to nothing.
  const WIN_FROM = new Date('2023-01-01');
  const WIN_TO = new Date('2030-01-01');
  const NOW = new Date('2026-08-13');

  const LANE_COLOR = {
    desig: '#12798B', rd: '#8E3B62', work: '#9A6A08', startup: '#1A8A9E', infra: '#5E7A10',
  };
  const HZ = {
    quick: { r: 5.5, label: 'Under a year' },
    mid: { r: 7, label: 'One to three years' },
    long: { r: 8.5, label: 'Three years or more' },
  };
  const HZ_ORDER = ['quick', 'mid', 'long'];

  let DATA = null, IN = [], PRE = [];
  const offLane = new Set(), offHz = new Set();
  let mode = null, lastW = 0, tip = null;

  const viz = document.getElementById('viz');
  const panel = document.getElementById('panel');
  const scrim = document.getElementById('scrim');

  const NS = 'http://www.w3.org/2000/svg';
  const el = (t, a, txt) => {
    const n = document.createElementNS(NS, t);
    for (const k in a) if (a[k] != null) n.setAttribute(k, a[k]);
    if (txt != null) n.textContent = txt;
    return n;
  };
  const h = (t, a, kids) => {
    const n = document.createElement(t);
    for (const k in (a || {})) {
      if (k === 'class') n.className = a[k];
      else if (k === 'text') n.textContent = a[k];
      else if (k.startsWith('on')) n.addEventListener(k.slice(2), a[k]);
      else if (a[k] != null) n.setAttribute(k, a[k]);
    }
    (kids || []).forEach((c) => n.appendChild(c));
    return n;
  };

  /* ------------------------------------------------------------- 1 data */

  // Show the date at the precision it is actually known to. An event recorded
  // only to its year is not a 1 January event, and drawing it as one is a lie
  // the reader cannot see.
  const MON = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
  function showDate(e) {
    const d = new Date(e.date);
    if (e.datePrecision === 'day') return `${d.getUTCDate()} ${MON[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
    if (e.datePrecision === 'month') return `${MON[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
    return e.dateDisplay;
  }
  const precNote = (e) => e.datePrecision === 'day' ? null
    : e.datePrecision === 'month' ? 'Recorded to the month; placed mid-month.'
    : 'Recorded to the year only; placed mid-year.';

  const visible = (e) => !offLane.has(e.laneKey) && !(e.horizon && offHz.has(e.horizon));

  /* ----------------------------------------------------------- 2 layout */

  // Pack events into sub-rows inside their lane so dots never sit on top of each
  // other. Greedy first-fit by x — the same approach a Gantt uses for bars.
  function pack(events, x, minGap) {
    const rowsEnd = [];
    events.forEach((e) => {
      const cx = x(new Date(e.date));
      let row = rowsEnd.findIndex((end) => cx - end >= minGap);
      if (row === -1) { row = rowsEnd.length; rowsEnd.push(-1e9); }
      rowsEnd[row] = cx;
      e._row = row; e._cx = cx;
    });
    return Math.max(1, rowsEnd.length);
  }

  /* ----------------------------------------------------------- 3 render */

  function render() {
    const w = viz.clientWidth;
    if (!w) return;
    const want = w < CARD_BREAKPOINT ? 'cards' : 'diagram';
    if (want === mode && Math.abs(w - lastW) < 2) return;
    mode = want; lastW = w;
    viz.textContent = '';
    (want === 'cards' ? renderCards : renderDiagram)(w);
  }

  function renderDiagram(W) {
    const L = { left: 208, right: 26, top: 46, bot: 42, laneGap: 10, rowH: 30, padY: 16 };
    const plotW = W - L.left - L.right;
    const span = WIN_TO - WIN_FROM;
    const x = (d) => L.left + ((Math.min(Math.max(d, WIN_FROM), WIN_TO) - WIN_FROM) / span) * plotW;

    const lanes = DATA.lanes.map((ln) => {
      const evs = IN.filter((e) => e.laneKey === ln.key && visible(e))
        .sort((a, b) => new Date(a.date) - new Date(b.date));
      const nRows = pack(evs, x, 19);
      return { ...ln, evs, nRows, all: IN.filter((e) => e.laneKey === ln.key).length };
    });

    let y = L.top;
    lanes.forEach((ln) => { ln.y = y; ln.h = ln.nRows * L.rowH + L.padY * 2; y += ln.h + L.laneGap; });
    const H = y + L.bot;

    const svg = el('svg', { viewBox: `0 0 ${W} ${H}`, role: 'img',
      'aria-label': ariaSummary() });

    // year gridlines + labels
    for (let yr = 2023; yr <= 2030; yr++) {
      const gx = x(new Date(`${yr}-01-01`));
      svg.appendChild(el('line', { class: 'axis-rule', x1: gx, x2: gx, y1: L.top - 14, y2: y - L.laneGap }));
      if (yr < 2030) svg.appendChild(el('text', { class: 'axis-y', x: gx + 7, y: L.top - 20 }, yr));
    }

    // lane bands + names
    lanes.forEach((ln, i) => {
      svg.appendChild(el('rect', { class: 'lane-band' + (i % 2 ? ' alt' : ''),
        x: 0, y: ln.y, width: W, height: ln.h, rx: 8 }));
      svg.appendChild(el('text', { class: 'lane-name', x: 0, y: ln.y + 24,
        fill: LANE_COLOR[ln.key] }, ln.name));
      const shown = ln.evs.length;
      svg.appendChild(el('text', { class: 'lane-count', x: 0, y: ln.y + 45 },
        shown === ln.all ? `${shown} events` : `${shown} of ${ln.all} events`));
    });

    // the "as of" rule — bars/dots to its right are scheduled, not delivered
    const nx = x(NOW);
    svg.appendChild(el('line', { class: 'now-rule', x1: nx, x2: nx, y1: L.top - 14, y2: y - L.laneGap }));
    svg.appendChild(el('text', { class: 'now-lab', x: nx + 8, y: y - L.laneGap + 20 }, 'Today'));

    // events
    lanes.forEach((ln) => {
      const g = el('g', {});
      ln.evs.forEach((e) => {
        const cy = ln.y + L.padY + e._row * L.rowH + L.rowH / 2;
        const r = (HZ[e.horizon] || HZ.mid).r;
        const node = el('g', { class: 'ev' + (e.delivered ? '' : ' fwd'), 'data-id': e.id,
          style: `--c:${LANE_COLOR[ln.key]}`,
          tabindex: '0', role: 'button',
          'aria-label': `${showDate(e)}. ${e.title}.` + (e.delivered ? '' : ' Scheduled, not delivered.') });
        node.appendChild(el('circle', { class: 'hit', cx: e._cx, cy, r: Math.max(13, r + 7) }));
        node.appendChild(el('circle', { class: 'dot', cx: e._cx, cy, r, fill: LANE_COLOR[ln.key],
          stroke: e.delivered ? '#fff' : LANE_COLOR[ln.key] }));
        // A white ring on a pale lane band still needs an anchor at small radii, or it
        // reads as a hole in the chart rather than a mark on it.
        if (!e.delivered) node.appendChild(el('circle', { class: 'pip', cx: e._cx, cy, r: 1.6,
          fill: LANE_COLOR[ln.key] }));
        g.appendChild(node);
      });
      svg.appendChild(g);
    });

    viz.appendChild(svg);
    wireEvents(svg);
    buildLegend();
  }

  function renderCards(W) {
    const list = h('div', { class: 'cards' });
    IN.filter(visible).slice().reverse().forEach((e) => {
      const c = h('div', { class: 'card', style: `border-left-color:${LANE_COLOR[e.laneKey]}` }, [
        h('div', { class: 'c-d', text: showDate(e) }),
        h('div', { class: 'c-t', text: e.title }),
        h('div', { class: 'c-o', text: `${e.lane} · ${e.org}` }),
      ]);
      if (!e.delivered) c.appendChild(h('span', { class: 'c-f', text: 'Scheduled, not delivered' }));
      list.appendChild(c);
    });
    viz.appendChild(list);
    buildLegend();
  }

  function ariaSummary() {
    const n = IN.filter(visible).length;
    const fwd = IN.filter((e) => visible(e) && !e.delivered).length;
    return `Timeline of ${n} public events from 2023 to 2029, in five workstream lanes: ` +
      DATA.lanes.map((l) => l.name).join(', ') + '. Each dot is one dated event; dot size shows how ' +
      `long that kind of work takes to show a result. ${fwd} events are hollow because they are ` +
      'scheduled, not delivered. A dashed rule marks 13 August 2026. The same record is in the table below.';
  }

  /* -------------------------------------------------------- 4 table + csv */

  function buildTable() {
    const tb = document.querySelector('#dtable tbody');
    tb.textContent = '';
    IN.filter(visible).forEach((e) => {
      tb.appendChild(h('tr', {}, [
        h('td', { class: 't-date', text: showDate(e) }),
        h('td', { text: e.title }),
        h('td', { class: 't-lane', style: `color:${LANE_COLOR[e.laneKey]}`, text: e.lane }),
        h('td', { text: e.org }),
        h('td', { class: 't-st', text: e.delivered ? 'Delivered' : 'Scheduled' }),
      ]));
    });
  }

  document.getElementById('csv').addEventListener('click', () => {
    const q = (s) => `"${String(s == null ? '' : s).replace(/"/g, '""')}"`;
    const rows = [['Date', 'Date precision', 'Event', 'Workstream', 'Organization', 'Status']
      .map(q).join(',')];
    IN.filter(visible).forEach((e) => rows.push([e.dateDisplay, e.datePrecision, e.title, e.lane,
      e.org, e.delivered ? 'Delivered' : 'Scheduled'].map(q).join(',')));
    const blob = new Blob([rows.join('\n')], { type: 'text/csv;charset=utf-8' });
    const a = h('a', { href: URL.createObjectURL(blob), download: 'pic-timeline.csv' });
    document.body.appendChild(a); a.click(); a.remove();
  });

  /* ------------------------------------------------------ 5 interaction */

  function wireEvents(svg) {
    svg.querySelectorAll('.ev').forEach((n) => {
      const e = IN.find((x) => x.id === n.dataset.id);
      n.addEventListener('mouseenter', () => showTip(n, e));
      n.addEventListener('mouseleave', hideTip);
      n.addEventListener('focus', () => showTip(n, e));
      n.addEventListener('blur', hideTip);
      n.addEventListener('click', () => openPanel(e));
      n.addEventListener('keydown', (ev) => {
        if (ev.key === 'Enter' || ev.key === ' ') { ev.preventDefault(); openPanel(e); }
      });
    });
  }

  function showTip(node, e) {
    hideTip();
    tip = h('div', { class: 'tip' }, [
      h('div', { class: 't-d', text: showDate(e) + (e.delivered ? '' : ' · scheduled') }),
      h('div', { class: 't-t', text: e.title }),
      h('div', { class: 't-o', text: `${e.lane} · ${e.org}` }),
    ]);
    viz.appendChild(tip);
    const b = node.getBoundingClientRect(), v = viz.getBoundingClientRect();
    const left = Math.min(Math.max(8, b.left - v.left - tip.offsetWidth / 2 + b.width / 2),
      v.width - tip.offsetWidth - 8);
    tip.style.left = left + 'px';
    tip.style.top = Math.max(4, b.top - v.top - tip.offsetHeight - 12) + 'px';
  }
  const hideTip = () => { if (tip) { tip.remove(); tip = null; } };

  function openPanel(e) {
    panel.textContent = '';
    panel.appendChild(h('button', { class: 'p-close', type: 'button', 'aria-label': 'Close',
      onclick: closePanel, text: '×' }));
    panel.appendChild(h('p', { class: 'p-kind', style: `color:${LANE_COLOR[e.laneKey]}`, text: e.lane }));
    panel.appendChild(h('h2', { id: 'panel-title', text: e.title }));
    const meta = h('dl', { class: 'p-meta' }, [
      h('div', {}, [h('dt', { text: 'Date' }), h('dd', { text: showDate(e) })]),
      h('div', {}, [h('dt', { text: 'Organization' }), h('dd', { text: e.org })]),
      h('div', {}, [h('dt', { text: 'Status' }),
        h('dd', { text: e.delivered ? 'Delivered' : 'Scheduled, not delivered' })]),
    ]);
    if (e.horizon) meta.appendChild(h('div', {}, [h('dt', { text: 'Time to a result' }),
      h('dd', { text: HZ[e.horizon].label })]));
    panel.appendChild(meta);
    const pn = precNote(e);
    if (pn) panel.appendChild(h('p', { class: 'p-note', text: pn }));
    if (!e.delivered) panel.appendChild(h('p', { class: 'p-note',
      text: 'This is a scheduled date drawn from the award or project record. It is not work already done.' }));
    panel.hidden = false; scrim.hidden = false;
    panel.querySelector('.p-close').focus();
  }
  function closePanel() { panel.hidden = true; scrim.hidden = true; }
  scrim.addEventListener('click', closePanel);
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape') { closePanel(); hideTip(); } });

  /* --------------------------------------------------------- filters */

  function buildFilters() {
    const lf = document.getElementById('lane-filters');
    DATA.lanes.forEach((ln) => {
      const b = h('button', { class: 'chip', type: 'button', 'aria-pressed': 'true',
        style: `color:${LANE_COLOR[ln.key]}`,
        onclick: () => { offLane.has(ln.key) ? offLane.delete(ln.key) : offLane.add(ln.key);
          b.setAttribute('aria-pressed', String(!offLane.has(ln.key))); refresh(); } }, [
        h('span', { class: 'sw', style: `background:${LANE_COLOR[ln.key]}` }),
        h('span', { text: ln.name }),
      ]);
      lf.appendChild(b);
    });
    const hf = document.getElementById('hz-filters');
    HZ_ORDER.forEach((k) => {
      const b = h('button', { class: 'chip', type: 'button', 'aria-pressed': 'true',
        onclick: () => { offHz.has(k) ? offHz.delete(k) : offHz.add(k);
          b.setAttribute('aria-pressed', String(!offHz.has(k))); refresh(); } },
        [h('span', { text: HZ[k].label })]);
      hf.appendChild(b);
    });
    const reset = document.getElementById('reset');
    reset.addEventListener('click', () => {
      offLane.clear(); offHz.clear();
      document.querySelectorAll('.chip').forEach((c) => c.setAttribute('aria-pressed', 'true'));
      refresh();
    });
  }

  function buildLegend() {
    const lg = document.getElementById('legend');
    lg.textContent = '';
    const grp = (title, items) => h('div', { class: 'grp' },
      [h('span', { class: 'lg-h', text: title }), ...items]);
    const svgDot = (fill, hollow) => {
      const s = document.createElementNS(NS, 'svg');
      s.setAttribute('width', '20'); s.setAttribute('height', '20');
      s.appendChild(el('circle', { cx: 10, cy: 10, r: 7, fill: hollow ? '#fff' : fill,
        stroke: hollow ? fill : '#fff', 'stroke-width': hollow ? 3 : 1.5 }));
      if (hollow) s.appendChild(el('circle', { cx: 10, cy: 10, r: 1.6, fill }));
      return s;
    };
    lg.appendChild(grp('Status', [
      h('span', { class: 'item' }, [svgDot('#12798B', false), h('span', { text: 'Delivered' })]),
      h('span', { class: 'item' }, [svgDot('#12798B', true), h('span', { text: 'Scheduled, not delivered' })]),
    ]));
    lg.appendChild(grp('Dot size — time to a visible result', HZ_ORDER.map((k) => {
      const s = document.createElementNS(NS, 'svg');
      s.setAttribute('width', '22'); s.setAttribute('height', '22');
      s.appendChild(el('circle', { cx: 11, cy: 11, r: HZ[k].r, fill: '#585955', stroke: '#fff' }));
      return h('span', { class: 'item' }, [s, h('span', { text: HZ[k].label })]);
    })));
    lg.hidden = false;
  }

  function refresh() {
    document.getElementById('reset').hidden = !(offLane.size || offHz.size);
    mode = null; render(); buildTable();
  }

  /* ------------------------------------------------------------- boot */

  loadData('timeline.json').then((d) => {
    DATA = d;
    const from = WIN_FROM.getTime();
    d.events.forEach((e) => { (new Date(e.date).getTime() >= from ? IN : PRE).push(e); });
    IN = IN.filter((e) => e.show || !e.delivered);

    const c = d.meta.counts;
    document.getElementById('topline').innerHTML = '';
    [[IN.length, 'public events shown'],
     [IN.filter((e) => e.delivered).length, 'delivered since 2023'],
     [IN.filter((e) => !e.delivered).length, 'scheduled ahead'],
     [d.lanes.length, 'workstreams, in parallel']].forEach(([n, l]) => {
      document.getElementById('topline').appendChild(h('li', {}, [
        h('b', { text: String(n) }), h('span', { text: l })]));
    });

    const pw = document.getElementById('pre-window');
    if (PRE.length) {
      pw.appendChild(h('p', {}, [
        h('b', { text: 'Before this window. ' }),
        document.createTextNode(PRE.map((e) => `${e.dateDisplay} ${e.title}`).join(' · ') +
          '. The timeline opens at the 2023 federal designation — the first event with money behind it.'),
      ]));
    }

    document.getElementById('m-source').textContent = d.meta.source;
    document.getElementById('m-public').textContent = d.meta.publicOnly;
    const notes = document.getElementById('m-notes');
    [['Each dot is one dated event, in the workstream that produced it.',],
     ['Dot size is how long that kind of work takes to show a result — not how important it is.'],
     ['Hollow dots to the right of the dashed rule are scheduled dates from the award record, not work already done.'],
     ['Dates are shown at the precision they were recorded. Some events are known only to a month or a year, and are placed mid-period rather than pretending to a day.'],
    ].forEach(([t]) => notes.appendChild(h('li', { text: t })));

    buildFilters(); buildTable(); render();
  }).catch((err) => {
    viz.textContent = '';
    viz.appendChild(h('p', { class: 'nojs',
      text: 'The timeline data could not be loaded. This page must be served over HTTP, not opened as a file.' }));
    console.error(err);
  });

  let t;
  window.addEventListener('resize', () => { clearTimeout(t); t = setTimeout(render, 130); });
})();
